import { readFile, readdir, mkdir, writeFile, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { gzipSync } from 'node:zlib';
import path from 'node:path';
const [checkout, componentTag] = process.argv.slice(2);
if (!checkout) throw Error('Usage: node scripts/package-components.mjs <patched T3 checkout>');
const root = path.resolve(checkout), web = path.join(root,'apps/web/dist');
const {version} = JSON.parse(await readFile('manifest.json','utf8'));
const releaseTag = componentTag ?? `components-${version}`;
if (!/^[A-Za-z0-9._-]+$/.test(releaseTag)) throw Error('Invalid component release tag.');
const hash = data => createHash('sha256').update(data).digest('hex');
const core = [];
async function collect(directory, prefix='') {
  for (const entry of (await readdir(directory,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))) {
    const relative = prefix+entry.name, source=path.join(directory,entry.name);
    if (entry.isDirectory()) await collect(source,relative+'/');
    else if (entry.isFile() && !relative.endsWith('.map')) {
      if (/\.(?:glb|otf)$/.test(relative) || /(?:docx|xlsx|pptx).*\.wasm$/.test(relative)) throw Error('Unwanted heavy asset: '+relative);
      const data=await readFile(source);core.push({path:relative,data:data.toString('base64'),sha256:hash(data)});
    }
  }
}
await collect(web);
if (core.some(file => file.path.includes('OfficeViewer') || file.path.includes('OfficeFilePreview'))) throw Error('Office preview is still bundled.');
const require=createRequire(path.join(root,'apps/web/package.json'));
const inter=path.dirname(require.resolve('@fontsource-variable/inter/package.json'));
const fonts=[];
async function fontFile(name,source){const data=await readFile(source);fonts.push({path:name,data:data.toString('base64'),sha256:hash(data)});}
let css=await readFile(path.join(inter,'index.css'),'utf8');
const selected=new Set([...css.matchAll(/url\((['"]?)\.\/files\/([^)'"\s]+)\1\)/g)].map(match=>match[2]));
for(const file of selected)await fontFile('fonts/'+file,path.join(inter,'files',file));
css=css.replace(/url\((['"]?)\.\/files\/([^)'"\s]+)\1\)/g,(_match,_quote,file)=>`url('/fonts/${file}')`);
await fontFile('fonts/SymbolsNerdFontMono-Regular.woff2',path.join(root,'apps/web/src/terminal/ghostty/fonts/SymbolsNerdFontMono-Regular.woff2'));
const licenses=(await readFile(path.join(inter,'LICENSE'),'utf8'))+'\n\n'+(await readFile(path.join(root,'apps/web/src/terminal/ghostty/fonts/LICENSE'),'utf8'));
for(const [name,text] of [['obsidian-extra-fonts.css',css+'\n:root { --obsidian-extra-fonts: 1; }\n'],['fonts/LICENSES.txt',licenses]])fonts.push({path:name,data:Buffer.from(text).toString('base64'),sha256:hash(text)});
await mkdir('dist/components',{recursive:true});
const assets={};
for(const [kind,files] of [['core',core],['fonts',fonts]]){
  const name=`t3-${kind}-${version}.json.gz`;
  const bytes=gzipSync(JSON.stringify({version,kind,files}),{level:9});
  await writeFile(path.join('dist/components',name),bytes);
  assets[kind]={version,kind,url:`https://github.com/kriss-spy/obsidian-t3code/releases/download/${releaseTag}/${name}`,sha256:hash(bytes),bytes:bytes.length};
}
await writeFile('src/component-release.ts',`// Generated by scripts/package-components.mjs. Downloads are pinned to this plugin version.\nimport type { ComponentAsset } from './components';\nexport const COMPONENT_ASSETS: Record<'core' | 'fonts', ComponentAsset> = ${JSON.stringify(assets,null,2)};\n`);
await writeFile('dist/components/assets.json',JSON.stringify(assets,null,2)+'\n');
console.log(JSON.stringify(assets,null,2));
